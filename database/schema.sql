--Accounts table
create table public.accounts (
  id bigint generated by default as identity not null,
  user_id uuid not null,
  name text not null,
  type text not null,
  created_at timestamp with time zone not null default now(),
  is_active boolean not null default true,
  constraint accounts_pkey primary key (id),
  constraint accounts_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade,
  constraint accounts_type_check check (
    (
      type = any (
        array[
          'debit'::text,
          'credit'::text
        ]
      )
    )
  )
) TABLESPACE pg_default;

--Transactions table
create table public.transactions (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  user_id uuid not null,
  account_id bigint not null,
  category_id bigint not null,
  amount numeric not null,
  date date not null,
  description text null,
  constraint transactions_pkey primary key (id),
  constraint transactions_account_id_fkey foreign KEY (account_id) references accounts (id),
  constraint transactions_category_id_fkey foreign KEY (category_id) references categories (id),
  constraint transactions_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade
) TABLESPACE pg_default;